-- ===== 3. TẠO ĐƠN + THANH TOÁN NHIỀU LẦN (rollback, không để lại dữ liệu) =====
BEGIN TRAN;

SELECT PRODUCT_ID, CURRENT_STOCK AS STOCK_BEFORE
FROM CATALOG.PRODUCT WHERE PRODUCT_ID IN (1, 2);

EXEC SALES.SP_CREATE_SALES_ORDER
     @employee_id = 51,
     @items = N'[{"productId":1,"quantity":2},{"productId":2,"quantity":1}]',
     @discount = 5000;

DECLARE @id INT = (SELECT MAX(SALES_ORDER_ID) FROM SALES.SALES_ORDER);

SELECT * FROM SALES.V_SALES_ORDER_TOTAL WHERE SALES_ORDER_ID = @id;   -- TOTAL 104000, NOT PAID

SELECT PRODUCT_ID, CURRENT_STOCK AS STOCK_AFTER
FROM CATALOG.PRODUCT WHERE PRODUCT_ID IN (1, 2);                      -- giảm 2 và 1

EXEC SALES.SP_ADD_PAYMENT @id, N'IN CASH', 50000;    -- còn thiếu 54000, vẫn NOT PAID
EXEC SALES.SP_ADD_PAYMENT @id, N'BY CARD', 54000;    -- đủ, chuyển PAID

SELECT * FROM SALES.PAYMENT WHERE SALES_ORDER_ID = @id;               -- 2 dòng

ROLLBACK;
GO

